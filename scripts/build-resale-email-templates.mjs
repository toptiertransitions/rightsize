// Copies the resale update email templates (email-templates/resale-updates,
// the source of truth) into lib/resale-emails/templates.generated.ts so the
// app can send them without reading files at runtime. Re-run after editing a
// template; a unit test fails if the two drift apart.
// Run: node scripts/build-resale-email-templates.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "email-templates/resale-updates");
const OUT = join(ROOT, "lib/resale-emails/templates.generated.ts");

const FILES = {
  "hands-on": "01-hands-on-complete.html",
  day30: "02-day-30-update.html",
  day60: "03-day-60-update.html",
  day90: "04-day-90-window-closed.html",
};

const entries = Object.entries(FILES).map(([type, file]) => {
  const raw = readFileSync(join(SRC, file), "utf8");
  const m = raw.match(/^<!-- Subject: (.+?) \| Sends: (.+?) -->\n/);
  if (!m) throw new Error(`${file}: first line must be <!-- Subject: ... | Sends: ... -->`);
  return `  ${JSON.stringify(type)}: {\n    file: ${JSON.stringify(file)},\n    subject: ${JSON.stringify(m[1])},\n    html: ${JSON.stringify(raw.slice(m[0].length))},\n  },`;
});

writeFileSync(OUT, `// GENERATED by scripts/build-resale-email-templates.mjs from
// email-templates/resale-updates. Do not edit by hand.
export const RESALE_TEMPLATES = {
${entries.join("\n")}
} as const;
`);
console.log(`wrote ${OUT}`);
